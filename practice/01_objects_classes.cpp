// ТЕМА 1: Класът е чертеж (тип), който обединява данни и поведение; обектът/инстанцията
// е конкретен екземпляр от този тип в паметта — много обекти от един клас, всеки със свои данни.
#include <iostream>
#include <string>

class Person {                 // дефиниция на клас = нов тип
public:
    std::string name;          // даннов член
    int age;
    void hi() { std::cout << name << " " << age << "\n"; }  // метод
};

int main() {
    Person a, b;               // два обекта (инстанции)
    a.name = "Ana";  a.age = 20;
    b.name = "Bob";  b.age = 21;
    a.hi();  b.hi();           // . = член на този обект
}
